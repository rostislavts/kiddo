import { spawnSync } from "node:child_process";
import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";

const result = spawnSync("supabase", ["status", "--output", "json"], {
  encoding: "utf8",
  env: { ...process.env, SUPABASE_TELEMETRY_DISABLED: "1" },
});
if (result.error || result.status !== 0) {
  throw new Error("Локалният Supabase не е достъпен. Стартирай Docker и npm run local:services.");
}
const status = JSON.parse(result.stdout);
for (const key of ["DB_URL", "API_URL"]) {
  if (!status[key] || !["127.0.0.1", "localhost"].includes(new URL(status[key]).hostname)) {
    throw new Error("Очаква се локална Supabase инсталация.");
  }
}
if (!status.ANON_KEY || !status.SERVICE_ROLE_KEY) {
  throw new Error("Липсват локалните Supabase Auth ключове.");
}
const updates = {
  NEXT_PUBLIC_APP_URL: "http://localhost:3001",
  DATABASE_URL: status.DB_URL,
  DATABASE_MIGRATION_URL: status.DB_URL,
  DATABASE_POOL_SIZE: "5",
  NEXT_PUBLIC_SUPABASE_URL: status.API_URL,
  NEXT_PUBLIC_SUPABASE_ANON_KEY: status.ANON_KEY,
  SUPABASE_SERVICE_ROLE_KEY: status.SERVICE_ROLE_KEY,
};
const source = existsSync(".env.local")
  ? ".env.local"
  : existsSync(".env")
    ? ".env"
    : ".env.example";
let content = readFileSync(source, "utf8");
for (const [key, value] of Object.entries(updates)) {
  const pattern = new RegExp(`^${key}=.*$`, "m");
  const line = `${key}=${value}`;
  content = pattern.test(content)
    ? content.replace(pattern, () => line)
    : `${content.trimEnd()}\n${line}\n`;
}
if (source !== ".env.local") {
  content = `# LOCAL DOCKER ONLY. Generated by npm run local:env; never commit.\n# App: http://localhost:3001 | Test email: http://127.0.0.1:55324\n${content}`;
  content = content.replace(
    /# Supabase:.*\n# URL-encode.*\n/,
    "# Local PostgreSQL container (port 55322).\n",
  );
  content = content.replace(
    /# Optional direct\/session.*\n/,
    "# Local direct database connection for migrations.\n",
  );
}
writeFileSync(".env.local", content, { mode: 0o600 });
chmodSync(".env.local", 0o600);
console.log(".env.local е попълнен за локалните PostgreSQL и Supabase Auth.");
console.log("Приложение: http://localhost:3001 | Тестови имейли: http://127.0.0.1:55324");
console.log("Съществуващите Paddle и AI настройки са запазени.");
